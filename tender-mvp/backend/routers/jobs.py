def _derive_mapping_status(
    mapping_out,
    price_out,
) -> MappingStatus:
    mapping_status_name = str(
        getattr(mapping_out, "classification", None)
        or getattr(mapping_out, "status", "mapping_unresolved")
    )
    mapped = {
        "mapped_and_priced": MappingStatus.mapped_and_priced,
        "mapped_price_unavailable": MappingStatus.mapped_price_unavailable,
        "mapping_ambiguous": MappingStatus.mapping_ambiguous,
        "mapping_unresolved": MappingStatus.mapping_unresolved,
        "invalid_quantity_or_unit": MappingStatus.invalid_quantity_or_unit,
        "non_billable_heading": MappingStatus.non_billable_heading,
        "non_billable_metadata": MappingStatus.non_billable_metadata,
        "resolved": MappingStatus.mapped_and_priced,
        "unresolved": MappingStatus.mapping_unresolved,
        "error": MappingStatus.mapping_unresolved,
    }
    mapping_status = mapped.get(mapping_status_name, MappingStatus.mapping_unresolved)

    if mapping_status in {MappingStatus.non_billable_heading, MappingStatus.non_billable_metadata}:
        return mapping_status
    if mapping_status in {MappingStatus.mapping_ambiguous, MappingStatus.mapping_unresolved, MappingStatus.invalid_quantity_or_unit}:
        return mapping_status
    if getattr(mapping_out, "master_item_id", None) is None:
        return MappingStatus.mapping_unresolved

    if price_out.status == "priced" and price_out.unit_price_str is not None and price_out.extended_amount_str is not None:
        return MappingStatus.mapped_and_priced
    if price_out.status == "unresolved":
        return MappingStatus.mapped_price_unavailable
    return MappingStatus.mapping_unresolved


async def _transition(db: AsyncSession, job: Job, stage: JobStatus) -> None:
    """Persist the visible state and its audit event atomically."""
    job.status = stage
    db.add(JobStageEvent(job_id=job.id, stage=stage.value))
    await db.commit()


async def _job_status_response(db: AsyncSession, job: Job) -> JobStatusResponse:
    source_count = int(await db.scalar(
        select(func.count()).select_from(BOQRow).where(BOQRow.job_id == job.id)
    ) or 0)
    billable_count = int(await db.scalar(
        select(func.count()).select_from(BOQRow).where(
            BOQRow.job_id == job.id, BOQRow.row_type == RowType.line_item,
        )
    ) or 0)
    issue_statuses = (
        MappingStatus.mapping_ambiguous,
        MappingStatus.mapping_unresolved,
        MappingStatus.invalid_quantity_or_unit,
    )
    mapping_unresolved = int(await db.scalar(
        select(func.count()).select_from(MappingResult).join(BOQRow).where(
            BOQRow.job_id == job.id,
            BOQRow.row_type == RowType.line_item,
            MappingResult.status.in_(issue_statuses),
        )
    ) or 0)
    pricing_unavailable = int(await db.scalar(
        select(func.count()).select_from(MappingResult).join(BOQRow).where(
            BOQRow.job_id == job.id,
            BOQRow.row_type == RowType.line_item,
            MappingResult.status == MappingStatus.mapped_price_unavailable,
        )
    ) or 0)
    pricing_conflicts = int(await db.scalar(
        select(func.count()).select_from(MappingResult).join(BOQRow).where(
            BOQRow.job_id == job.id,
            BOQRow.row_type == RowType.line_item,
            MappingResult.price_review_required.is_(True),
        )
    ) or 0)
    unresolved_total = int(await db.scalar(
        select(func.count()).select_from(MappingResult).join(BOQRow).where(
            BOQRow.job_id == job.id,
            BOQRow.row_type == RowType.line_item,
            or_(
                MappingResult.status.in_((*issue_statuses, MappingStatus.mapped_price_unavailable)),
                MappingResult.price_review_required.is_(True),
            ),
        )
    ) or 0)
    events = (await db.execute(
        select(JobStageEvent).where(JobStageEvent.job_id == job.id).order_by(JobStageEvent.id)
    )).scalars().all()
    return JobStatusResponse(
        job_id=job.id,
        status=job.status,
        filename=job.filename,
        error_message=job.error_message,
        row_count=source_count,
        unresolved_count=unresolved_total,
        source_row_count=source_count,
        billable_count=billable_count,
        structural_count=source_count - billable_count,
        mapping_unresolved_count=mapping_unresolved,
        pricing_unavailable_count=pricing_unavailable,
        pricing_conflict_count=pricing_conflicts,
        created_at=job.created_at,
        updated_at=job.updated_at,
        stage_sequence=[{"stage": event.stage, "occurred_at": event.occurred_at} for event in events],
    )


@router.post("/upload", response_model=JobStatusResponse)
async def upload_pdf(
    background_tasks: BackgroundTasks,
    file: UploadFile = File(...),
    db: AsyncSession = Depends(get_db),
):
    if not file.filename or not file.filename.lower().endswith(".pdf"):
        raise HTTPException(400, "Only PDF files are accepted")

    try:
        pdf_bytes = await file.read()
    except Exception as exc:
        raise HTTPException(400, "Failed to read uploaded file") from exc
    if not pdf_bytes:
        raise HTTPException(400, "Uploaded PDF is empty")

    job_id = str(uuid.uuid4())
    try:
        _persist_source_document(job_id, pdf_bytes)
    except OSError as exc:
        raise HTTPException(500, "Unable to store the source PDF securely") from exc
    job = Job(
        id=job_id,
        tenant_id=DEMO_TENANT_ID,
        filename=file.filename,
        status=JobStatus.uploaded,
    )
    try:
        db.add(job)
        db.add(JobStageEvent(job_id=job_id, stage=JobStatus.uploaded.value))
        await db.commit()
    except Exception:
        _document_path(job_id).unlink(missing_ok=True)
        raise

    background_tasks.add_task(_process_job, job_id, pdf_bytes, file.filename)

    return await _job_status_response(db, job)


@router.post("/uat-validation-import", response_model=JobStatusResponse)
async def import_uat_validation_pdf(
    file: UploadFile = File(...),
    db: AsyncSession = Depends(get_db),
):
    """Create a labelled UAT persistence project without paid provider calls.

    This route is fail-closed outside UAT and must be explicitly enabled. It
    stores the supplied real PDF while loading the already-verified canonical
    source/pricing evidence fixture. It never counts as live Azure/OpenAI proof.
    """
    environment = os.getenv("APP_ENV", os.getenv("ENVIRONMENT", "")).strip().lower()
    enabled = os.getenv("ALLOW_UAT_FIXTURE_IMPORT", "").strip().lower() in {"1", "true", "yes"}
    if environment != "uat" or not enabled:
        raise HTTPException(403, "UAT validation import is disabled")
    if not file.filename or not file.filename.lower().endswith(".pdf"):
        raise HTTPException(400, "Only PDF files are accepted")
    pdf_bytes = await file.read()
    if not pdf_bytes.startswith(b"%PDF-"):
        raise HTTPException(400, "Uploaded file does not have a valid PDF signature")
    try:
        import fitz
        with fitz.open(stream=pdf_bytes, filetype="pdf") as document:
            if document.page_count != 4:
                raise HTTPException(400, "UAT validation requires the four-page sample PDF")
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(400, "Uploaded PDF could not be validated") from exc

    baseline = json.loads(UAT_BASELINE_FIXTURE.read_text(encoding="utf-8"))
    raw_azure = json.loads(HISTORICAL_AZURE_FIXTURE.read_text(encoding="utf-8"))
    rows = baseline.get("rows") or []
    if len(rows) != 95 or sum(bool(row.get("billable")) for row in rows) != 82:
        raise HTTPException(500, "Checked-in UAT source contract is invalid")

    job_id = str(uuid.uuid4())
    _persist_source_document(job_id, pdf_bytes)
    now = datetime.now(timezone.utc)
    job = Job(
        id=job_id,
        tenant_id=f"uat-validation-{job_id}",
        filename=f"[UAT VALIDATION - NOT OFFICIAL] {file.filename}",
        status=JobStatus.needs_review,
    )
    db.add(job)
    for stage in (
        JobStatus.uploaded, JobStatus.parsing, JobStatus.mapping,
        JobStatus.pricing, JobStatus.needs_review,
    ):
        db.add(JobStageEvent(job_id=job_id, stage=stage.value))
    db.add(ParsedDocument(
        job_id=job_id,
        raw_json=json.dumps(raw_azure, ensure_ascii=False),
        page_count=4,
        model_id="prebuilt-layout",
        api_version="2024-11-30",
    ))
    try:
        for source in rows:
            row = BOQRow(
                job_id=job_id,
                row_id=f"uat-source-{int(source['source_index']):03d}",
                row_number=source.get("stt"),
                section_path=source.get("section_path") or "",
                description_vi=source.get("description") or "",
                unit_raw=source.get("unit") or None,
                quantity_raw=source.get("quantity_raw") or None,
                quantity=float(source["quantity"]) if source.get("quantity") not in (None, "") else None,
                page=int(source.get("page") or 1),
                region=json.dumps(source.get("polygon") or []),
                row_type=RowType.line_item if source.get("billable") else RowType.metadata,
                doc_order=int(source["source_index"]),
                source_origin=source.get("source_origin") or "azure_document_intelligence",
                source_provenance=source.get("source_provenance"),
                azure_polygon_available=bool(source.get("azure_polygon_available", True)),
            )
            db.add(row)
            await db.flush()

            master = None
            if source.get("treatment") == "mapped_and_priced":
                master = MasterItem(
                    tenant_id=job.tenant_id,
                    version="source-20260927",
                    item_code=source.get("mapped_work_item") or f"UAT.{source['source_index']}",
                    description_vi=source.get("mapped_description") or source.get("description") or "",
                    unit=source.get("unit") or "",
                    unit_price=float(source["unit_price"]),
                    formula_ref=source.get("formula_ref"),
                    source_sheet=source.get("price_source_reference"),
                    created_by="source-evidence-import",
                    created_at=now,
                    last_updated_by="source-evidence-import",
                    last_updated_at=now,
                    price_source_reference=source.get("price_source_reference"),
                    price_effective_date=None,
                    approval_status="source_verified",
                )
                db.add(master)
                await db.flush()

            is_billable = bool(source.get("billable"))
            status = (
                MappingStatus.mapped_and_priced if master else
                MappingStatus.mapped_price_unavailable if is_billable else
                MappingStatus.non_billable_metadata
            )
            db.add(MappingResult(
                boq_row_id=row.id,
                master_item_id=master.id if master else None,
                status=status,
                confidence=1.0 if master or not is_billable else None,
                evidence="Pre-validated UAT persistence fixture; not a live provider result.",
                unresolved_reason=source.get("reason") if is_billable and not master else None,
                unit_price_str=str(source["unit_price"]) if master else None,
                extended_amount_str=str(source["extension"]) if master else None,
                price_source="source_reconciliation_fixture" if master else None,
                formula_ref=source.get("formula_ref"),
                master_version="source-20260927" if master else None,
                pricing_availability="available" if master else ("not_available" if is_billable else "not_applicable"),
                price_effective_date=None,
                price_source_reference=source.get("price_source_reference") if master else None,
                price_last_updated_by="source-evidence-import" if master else None,
                price_last_updated_at=now if master else None,
                mapping_last_updated_by="source-evidence-import",
                mapping_last_updated_at=now,
                mapped_by="source-evidence-import" if master else None,
            ))
        await db.commit()
    except Exception:
        await db.rollback()
        _document_path(job_id).unlink(missing_ok=True)
        raise

    return await _job_status_response(db, job)


@router.get("/{job_id}/document")
async def get_source_document(job_id: str, db: AsyncSession = Depends(get_db)):
    """Stream the original PDF inline for authenticated review."""
    job = await db.get(Job, job_id)
    if not job:
        raise HTTPException(404, "Job not found")
    document_path = _document_path(job_id)
    if not document_path.is_file():
        raise HTTPException(
            404,
            "Source PDF is unavailable for this job (it may predate document storage)",
        )
    return FileResponse(
        document_path,
        media_type="application/pdf",
        filename=job.filename,
        content_disposition_type="inline",
        headers={"Cache-Control": "private, no-store"},
    )


@router.get("/{job_id}/document/metadata", response_model=DocumentMetadata)
async def get_document_metadata(job_id: str, db: AsyncSession = Depends(get_db)):
    job = await db.get(Job, job_id)
    if not job:
        raise HTTPException(404, "Job not found")
    parsed_document = await db.scalar(
        select(ParsedDocument).where(ParsedDocument.job_id == job_id)
    )
    if not parsed_document:
        raise HTTPException(404, "Parsed document metadata not found")
    try:
        raw = json.loads(parsed_document.raw_json)
    except json.JSONDecodeError as exc:
        raise HTTPException(500, "Stored parser metadata is invalid") from exc
    analyze = raw.get("analyzeResult", raw)
    pages = [
        DocumentPage(
            page=int(page.get("pageNumber", index + 1)),
            width=float(page.get("width", 1)),
            height=float(page.get("height", 1)),
            unit=str(page.get("unit", "inch")),
        )
        for index, page in enumerate(analyze.get("pages", []))
    ]
    return DocumentMetadata(page_count=parsed_document.page_count, pages=pages)


@router.get("/{job_id}/document/pages/{page_number}.png")
async def render_document_page(
    job_id: str,
    page_number: int,
    db: AsyncSession = Depends(get_db),
):
    """Render one protected source page for an overlay-capable review UI."""
    job = await db.get(Job, job_id)
    if not job:
        raise HTTPException(404, "Job not found")
    document_path = _document_path(job_id)
    if not document_path.is_file():
        raise HTTPException(404, "Source PDF is unavailable for this job")
    if page_number < 1:
        raise HTTPException(400, "page_number must be at least 1")
    try:
        import fitz
    except ImportError as exc:  # pragma: no cover - packaging guard
        raise HTTPException(503, "PDF page rendering is not installed") from exc
    try:
        with fitz.open(document_path) as document:
            if page_number > document.page_count:
                raise HTTPException(404, "PDF page not found")
            page = document.load_page(page_number - 1)
            pixmap = page.get_pixmap(matrix=fitz.Matrix(1.65, 1.65), alpha=False)
            png_bytes = pixmap.tobytes("png")
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(422, "Source PDF could not be rendered") from exc
    return Response(
        content=png_bytes,
        media_type="image/png",
        headers={"Cache-Control": "private, no-store"},
    )


