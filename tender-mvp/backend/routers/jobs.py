def _document_storage_dir() -> Path:
    """Return the non-public source-document store.

    The directory is configurable for UAT persistent volumes.  It is never
    mounted as static content; documents are only served through the protected
    jobs API.
    """
    configured = os.getenv("DOCUMENT_STORAGE_DIR", "").strip()
    if configured:
        return Path(configured).expanduser().resolve()
    return (Path(__file__).resolve().parents[2] / "runtime" / "documents").resolve()


def _document_path(job_id: str) -> Path:
    # job_id is generated by this service and only used as a filename.  UUID
    # parsing prevents traversal if a caller supplies an arbitrary path value.
    try:
        safe_id = str(uuid.UUID(job_id))
    except ValueError as exc:
        raise HTTPException(404, "Job not found") from exc
    return _document_storage_dir() / f"{safe_id}.pdf"


def _persist_source_document(job_id: str, pdf_bytes: bytes) -> None:
    destination = _document_path(job_id)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix(".pdf.part")
    try:
        temporary.write_bytes(pdf_bytes)
        temporary.replace(destination)
    finally:
        if temporary.exists():
            temporary.unlink()


